-- Permite combinar igualdade (room_id) e sobreposição (period) no mesmo índice GiST.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE rooms (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      text NOT NULL,
  city      text NOT NULL,
  capacity  integer NOT NULL CHECK (capacity > 0),
  timezone  text NOT NULL DEFAULT 'America/Sao_Paulo'
);

CREATE TABLE users (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   text NOT NULL,
  email  text NOT NULL UNIQUE
);

CREATE TABLE reservations (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id          integer NOT NULL REFERENCES rooms (id),
  user_id          integer NOT NULL REFERENCES users (id),
  -- Intervalo semiaberto [início, fim): 10:00-11:00 e 11:00-12:00 não conflitam.
  period           tstzrange NOT NULL,
  status           text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'cancelled')),
  idempotency_key  text NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  cancelled_at     timestamptz,

  CONSTRAINT reservations_period_bounded
    CHECK (NOT isempty(period) AND NOT lower_inf(period) AND NOT upper_inf(period)),

  -- A garantia central do sistema: o banco recusa duas reservas confirmadas
  -- sobrepostas na mesma sala. Reservas canceladas ficam fora da restrição,
  -- então o horário é liberado no instante em que o cancelamento é gravado.
  CONSTRAINT reservations_no_overlap
    EXCLUDE USING gist (room_id WITH =, period WITH &&) WHERE (status = 'confirmed'),

  -- Uma nova tentativa da mesma confirmação nunca cria uma segunda reserva.
  CONSTRAINT reservations_user_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX reservations_by_user ON reservations (user_id, lower(period) DESC);

-- Eventos gravados na mesma transação da reserva e entregues depois por um worker.
CREATE TABLE outbox (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  type             text NOT NULL,
  payload          jsonb NOT NULL,
  status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'dead')),
  attempts         integer NOT NULL DEFAULT 0,
  -- Também funciona como concessão: ao pegar um evento, o worker empurra esta
  -- data para frente; se ele morrer, o evento volta a ficar disponível sozinho.
  next_attempt_at  timestamptz NOT NULL DEFAULT now(),
  last_error       text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  sent_at          timestamptz
);

CREATE INDEX outbox_ready ON outbox (next_attempt_at) WHERE status = 'pending';
